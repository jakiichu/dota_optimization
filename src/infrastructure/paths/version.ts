/**
 * Как называется эта сборка.
 *
 * Нужно затем, что сборку раздают людям. Получив «у меня цифры другие», первым
 * делом спрашивают «а версия какая», и без ответа разговор не идёт.
 *
 * Строку подставляет сборщик — тем же способом, что и признак упакованности:
 * идентификатора в исходниках не существует, поэтому проверять его можно
 * только через `typeof`. В дереве исходников версии нет и быть не должно —
 * там собирается то, что сейчас лежит на диске, а не то, что закоммичено.
 */

declare const FRAMELOSS_VERSION: string;

const UNPACKAGED = 'из исходников';

export function buildVersion(): string {
  return typeof FRAMELOSS_VERSION === 'undefined' ? UNPACKAGED : FRAMELOSS_VERSION;
}
