namespace Frameloss.Sidecar.Sensors;

/// <summary>
/// Сколько процессора заняла одна программа за прошедший интервал.
/// </summary>
/// <remarks>
/// Именно программа, а не процесс: браузер с дюжиной вкладок — это дюжина
/// процессов по три процента, и назвать виновником один из них неверно, а
/// занять ими весь список — бесполезно. Складываем по имени.
///
/// Проценты — от всего процессора, а не от одного ядра: «34%» на шестнадцати
/// потоках значит примерно пять занятых потоков, и это та величина, которую
/// человек видит в диспетчере задач.
///
/// Имя без пути намеренно. Путь — это уже опись установленного на машине, а
/// записи носят с компьютера на компьютер и прикладывают к письмам.
/// </remarks>
public sealed record ProcessSensorReading
{
    public required string Name { get; init; }

    /// <summary>Доля всего процессора за интервал, 0…100.</summary>
    public required double CpuPercent { get; init; }

    /// <summary>Сколько процессов с этим именем сложилось в строку.</summary>
    public required int ProcessCount { get; init; }
}
